import { expect, test } from '@playwright/test'

const credential = process.env.PORTAL_OPERATOR_TOKEN
if (!credential) {
  throw new Error('PORTAL_OPERATOR_TOKEN must be generated by the loopback fixture script')
}

test.beforeEach(async ({ page }) => {
  await page.goto('/portal.html')
  await expect(page.getByText('连接你的计算集群')).toBeVisible()
})

async function unlock(page: import('@playwright/test').Page, cluster = 'portal-ci', token = credential) {
  await page.locator('#cluster-id').fill(cluster)
  await page.locator('#operator-token').fill(token)
  await page.getByRole('button', { name: '授权读取' }).click()
}

test('operator can inspect actual scoped Go resources, evidence, projects and second page', async ({ page }) => {
  const operatorRequests: string[] = []
  page.on('request', request => {
    if (request.url().includes('/api/v1/')) operatorRequests.push(request.url())
  })
  await unlock(page)
  await expect(page.getByText('集群信息')).toBeVisible()
  await expect(page.getByText('portal-ci', { exact: true }).last()).toBeVisible()
  await expect(page.getByText('资源状态预览')).toBeVisible()
  await expect(page.getByText('secret-foreign')).toHaveCount(0)

  await page.getByRole('button', { name: /项目视图/ }).click()
  await expect(page.getByText('项目 / AI Initiatives')).toBeVisible()
  await expect(page.getByText('research', { exact: true })).toBeVisible()
  await expect(page.getByText('other-tenant', { exact: true })).toHaveCount(0)

  await page.getByRole('button', { name: /资源与工作负载/ }).click()
  await expect(page.getByText('已载入 120 条')).toBeVisible()
  const row = page.locator('.el-table__body tr').filter({ hasText: 'work-001' }).first()
  await row.click()
  await expect(page.getByText('job/work-001')).toBeVisible()
  await page.keyboard.press('Escape')

  await page.getByRole('button', { name: '继续加载下一页' }).click()
  await expect(page.getByText('work-124', { exact: true })).toBeVisible()
  await expect(page.locator('.el-table__body tr')).toHaveCount(125)
  await expect(page.getByRole('button', { name: '继续加载下一页' })).toHaveCount(0)
  await expect(page.getByText('secret-foreign')).toHaveCount(0)
  expect(operatorRequests.length).toBeGreaterThanOrEqual(2)
  expect(operatorRequests.every(url => url.includes('/api/v1/operator/clusters/portal-ci/snapshot'))).toBe(true)

  await page.getByRole('button', { name: '锁定' }).click()
  await expect(page.getByText('连接你的计算集群')).toBeVisible()
  await expect(page.locator('#operator-token')).toHaveValue('')
  await expect(page.getByText('work-001')).toHaveCount(0)
})

test('invalid token and foreign cluster are rejected by live Go API before displaying inventory', async ({ page }) => {
  await unlock(page, 'portal-ci', 'invalid-token-with-at-least-32-characters')
  await expect(page.getByText('凭证无效或服务端未启用操作员预览')).toBeVisible()
  await expect(page.getByText('资源状态预览')).toHaveCount(0)

  await unlock(page, 'foreign-cluster', credential)
  await expect(page.getByText('当前凭证不能访问该集群，或该集群尚未注册')).toBeVisible()
  await expect(page.getByText('资源状态预览')).toHaveCount(0)

  const blocked = await page.evaluate(async () => {
    const resp = await fetch('/api/v1/operator/clusters/portal-ci/snapshot', { cache: 'no-store' })
    return resp.status
  })
  expect(blocked).toBe(401)
})

